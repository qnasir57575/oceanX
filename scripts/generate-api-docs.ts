function validateRegistry() {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const e of endpointList) {
    const key = `${e.method} ${e.path}`;
    if (seen.has(key)) problems.push(`Duplicate route ${key}`);
    seen.add(key);
    if (!CLIENT_MODULES.includes(e.client.module)) problems.push(`${e.operationId}: unknown client module ${e.client.module}`);
    if (e.request?.params && !/\{\w+\}/.test(e.path)) problems.push(`${e.operationId}: params schema but no {param} in path`);
  }
  if (problems.length) throw new Error(`Registry problems:\n- ${problems.join("\n- ")}`);
}

async function main() {
  validateRegistry();
  const routesFile = path.join(ROOT, "src/lib/api/routes.generated.ts");
  outputs.set(routesFile, generateRoutes());
  if (!CHECK) writeFileSync(routesFile, outputs.get(routesFile)!);

  const examples = await generateExamples();
  const failed = [...examples.entries()].filter(([, ex]) => ex.error);
  if (failed.length) {
    throw new Error(`Example requests failed against the mock API:\n${failed.map(([op, ex]) => `- ${op}: ${ex.error}`).join("\n")}`);
  }

  outputs.set(path.join(ROOT, "docs/openapi.yaml"), generateOpenApi(examples));

  const docFile = path.join(ROOT, "docs/API_DOCUMENTATION.md");
  let doc = readFileSync(docFile, "utf8");
  doc = replaceBlock(doc, "status-counts", statusCounts(), docFile);
  doc = replaceBlock(doc, "endpoint-table", endpointTable(), docFile);
  doc = replaceBlock(doc, "endpoint-reference", endpointReference(examples), docFile);
  outputs.set(docFile, doc);

  const handoffFile = path.join(ROOT, "docs/FRONTEND_HANDOFF.md");
  if (existsSync(handoffFile)) {
    outputs.set(handoffFile, replaceBlock(readFileSync(handoffFile, "utf8"), "page-api-map", pageApiMap(), handoffFile));
  }

  let stale = 0;
  for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (current === content) continue;
    if (CHECK) {
      stale++;
      console.error(`✗ ${path.relative(ROOT, file)} is out of date.`);
    } else {
      writeFileSync(file, content);
      console.log(`✓ wrote ${path.relative(ROOT, file)}`);
    }
  }
  if (CHECK && stale) {
    console.error("\nAPI artifacts are stale. Run `npm run api:generate` and commit the result.");
    process.exit(1);
  }
  const counts = STATUSES.map((s) => `${s}=${endpointList.filter((e) => e.status === s).length}`).join(" ");
  console.log(`${CHECK ? "✓ API artifacts are up to date." : "Done."} ${endpointList.length} endpoints (${counts}).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
