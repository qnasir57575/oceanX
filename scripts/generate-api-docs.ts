function generateRoutes(): string {
  const lines = endpointList.map((e) => `  ${e.operationId}: { method: "${e.method}", path: "${e.path}" },`);
  return [
    "// AUTO-GENERATED by scripts/generate-api-docs.ts — do not edit. Run `npm run api:generate`.",
    "// Method/path for every operation, so the browser client does not need to bundle the Zod contracts.",
    'import type { OperationId } from "@/contracts/registry";',
    "",
    "export const ROUTES = {",
    ...lines,
    '} as const satisfies Record<OperationId, { method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE"; path: string }>;',
    "",
  ].join("\n");
}

// ─── 2. Examples from the mock API ──────────────────────────────────────────

type Example = { params?: Record<string, string>; query?: Record<string, unknown>; body?: unknown; response?: unknown; error?: string };

async function generateExamples(): Promise<Map<string, Example>> {
  process.env.NEXT_PUBLIC_MOCK_SCENARIO = "normal";
  const store = await import("../src/mocks/store");
  const { mockTransport } = await import("../src/mocks/transport");
  const { buildPath } = await import("../src/contracts/registry");
  store.setMockClock(FIXED_NOW);

  const sessionFor = (e: EndpointDefinition): string | null => {
    const memberOps = ["getSession", "changePassword", "updateMyProfile", "logout"];
    if (memberOps.includes(e.operationId)) return "member";
    if (e.operationId === "withdrawSubmission") return "researcher";
    if (e.auth !== "REQUIRED") return null;
    if (!e.roles || e.roles.includes("ADMIN")) return "admin";
    return e.roles[0].toLowerCase();
  };

  const run = async (e: EndpointDefinition, params: Record<string, string> | undefined, body: unknown) =>
    mockTransport({
      operationId: e.operationId as OperationId,
      method: e.method,
      path: buildPath(e.path, params),
      queryString: serializeQuery(e.example?.query),
      body,
      noDelay: true,
    });

  const examples = new Map<string, Example>();
  for (const e of endpointList) {
    store.resetMockStore();
    store.setMockClock(FIXED_NOW);
    store.setMockSessionUser(sessionFor(e));
    let params = e.example?.params;
    try {
      // Upload steps need a ticket created first.
      if (e.operationId === "putUploadContent" || e.operationId === "completeUpload") {
        const ticket = (await mockTransport({
          operationId: "createUpload",
          method: "POST",
          path: "/uploads",
          queryString: "",
          body: { fileName: "demo-figure.png", contentType: "image/png", sizeBytes: 482113, purpose: "COVER_IMAGE" },
          noDelay: true,
        })) as { data: { fileId: string } };
        params = { id: ticket.data.fileId };
        if (e.operationId === "completeUpload") await run({ ...e, operationId: "putUploadContent", method: "PUT", path: "/uploads/{id}/content" }, params, undefined);
      }
      const response = e.response.schema ? await run(e, params, e.example?.body) : undefined;
      examples.set(e.operationId, { params, query: e.example?.query, body: e.example?.body, response });
    } catch (err) {
      examples.set(e.operationId, { params, query: e.example?.query, body: e.example?.body, error: String((err as Error).message) });
    }
  }
  store.resetMockStore();
  return examples;
}

/** Trim long arrays so examples stay readable. */
function trimExample(value: unknown, depth = 0): unknown {
  if (Array.isArray(value)) {
    const max = depth === 1 ? 2 : 3; // top-level `data` arrays → 2 items
    const items = value.slice(0, max).map((v) => trimExample(v, depth + 1));
    return items;
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, trimExample(v, depth + 1)]));
  }
  return value;
}

