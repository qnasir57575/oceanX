function generateOpenApi(examples: Map<string, Example>): string {
  const paths: ZodOpenApiPathsObject = {};
  for (const e of endpointList) {
    const ex = examples.get(e.operationId);
    const statusNote =
      e.status === "IMPLEMENTED"
        ? ""
        : `\n\n**Status: ${e.status}.** ${e.status === "PLANNED" ? "Not implemented yet — this is the agreed contract; examples are illustrative." : e.status === "IN_PROGRESS" ? "Partially implemented; may change." : `Deprecated${e.deprecated?.replacement ? ` — use ${e.deprecated.replacement}` : ""}.`}`;
    const rolesNote = e.auth === "REQUIRED" ? `\n\n**Roles:** ${e.roles ? e.roles.join(", ") : "any logged-in user"}.` : "";
    const responses: Record<string, unknown> = {
      [String(e.response.status)]: {
        description: e.response.description,
        ...(e.response.headers
          ? { headers: z.object(Object.fromEntries(Object.entries(e.response.headers).map(([k, v]) => [k, z.string().meta({ description: v })]))) }
          : {}),
        ...(e.response.schema
          ? { content: { "application/json": { schema: e.response.schema, ...(ex?.response ? { example: trimExample(ex.response) } : {}) } } }
          : {}),
      },
    };
    for (const [status, reason] of Object.entries(e.errors)) {
      responses[status] = {
        description: `\`${ERROR_STATUS_CODES[Number(status) as ErrorStatus]}\` — ${reason}`,
        content: { "application/json": { schema: ErrorResponseSchema } },
      };
    }
    const req = e.request;
    const op: ZodOpenApiOperationObject = {
      operationId: e.operationId,
      summary: e.status === "IMPLEMENTED" ? e.summary : `${e.summary} [${e.status}]`,
      description: e.description + rolesNote + statusNote,
      tags: [e.tag],
      ...(e.status === "DEPRECATED" ? { deprecated: true } : {}),
      security: e.auth === "REQUIRED" ? [{ sessionCookie: [] }] : e.auth === "OPTIONAL" ? [{}, { sessionCookie: [] }] : [],
      ...(req?.params || req?.query ? { requestParams: { ...(req.params ? { path: req.params } : {}), ...(req.query ? { query: req.query } : {}) } } : {}),
      ...(req?.body
        ? { requestBody: { required: true, content: { "application/json": { schema: req.body, ...(ex?.body ? { example: ex.body } : {}) } } } }
        : req?.bodyContentType === "application/octet-stream"
          ? { requestBody: { required: true, content: { "application/octet-stream": { schema: { type: "string", format: "binary" } } } } }
          : {}),
      responses: responses as ZodOpenApiOperationObject["responses"],
      "x-status": e.status,
      "x-auth": e.auth,
      ...(e.roles ? { "x-roles": [...e.roles] } : {}),
      ...(e.rateLimit ? { "x-rate-limit": `${e.rateLimit.limit} requests / ${e.rateLimit.windowSeconds}s per ${e.rateLimit.scope}` } : {}),
      "x-frontend-pages": [...e.frontend.pages],
      "x-client-function": `${e.client.fn}() in src/lib/api/${e.client.module}.ts`,
    } as ZodOpenApiOperationObject;
    const key = e.path as `/${string}`;
    paths[key] = { ...(paths[key] ?? {}), [e.method.toLowerCase()]: op };
  }

  const doc = createDocument(
    {
      openapi: "3.1.0",
      info: {
        title: "OceanX Polar Science Portal API",
        version: API_VERSION,
        description:
          "SIH26063 — Integrated Polar Science Outreach, Knowledge Repository and Media Dissemination Portal.\n\n" +
          "GENERATED from src/contracts by `npm run api:generate` — do not edit by hand.\n\n" +
          "Every operation has an `x-status` of IMPLEMENTED, IN_PROGRESS, PLANNED or DEPRECATED. " +
          "Only IMPLEMENTED operations are served by the backend today; PLANNED operations describe the agreed " +
          "contract and are available through the mock API (NEXT_PUBLIC_USE_MOCK_API=true).\n\n" +
          "Authentication uses the httpOnly `oceanx_session` cookie set by POST /auth/login. " +
          "All responses use the envelope `{ success: true, data, … }` or `{ success: false, error }`.",
      },
      servers: [
        { url: "http://localhost:3000/api/v1", description: "Local development" },
        { url: API_BASE_PATH, description: "Same origin as the web app" },
      ],
      tags: API_TAGS.map((name) => ({ name, description: TAG_DESCRIPTIONS[name] })),
      paths,
      components: {
        securitySchemes: {
          sessionCookie: {
            type: "apiKey",
            in: "cookie",
            name: "oceanx_session",
            description: "httpOnly session cookie set by POST /auth/login or /auth/register.",
          },
        },
      },
    },
    { reused: "ref" },
  );
  return (
    "# AUTO-GENERATED by scripts/generate-api-docs.ts from src/contracts — do not edit.\n" +
    "# Regenerate with `npm run api:generate`; CI fails if this file is stale (`npm run api:check`).\n" +
    stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false })
  );
}

// ─── 4. Markdown ────────────────────────────────────────────────────────────

type JS = {
  type?: string | string[];
  $ref?: string;
  anyOf?: JS[];
  oneOf?: JS[];
  enum?: unknown[];
  const?: unknown;
  format?: string;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  maxLength?: number;
  minItems?: number;
  maxItems?: number;
  pattern?: string;
  default?: unknown;
  description?: string;
  properties?: Record<string, JS>;
  required?: string[];
  items?: JS;
  additionalProperties?: JS | boolean;
  $defs?: Record<string, JS>;
};

const MAX_SAFE = Number.MAX_SAFE_INTEGER;

function toJson(schema: z.ZodType, io: "input" | "output"): JS {
  return z.toJSONSchema(schema, { io, unrepresentable: "any", target: "draft-2020-12" }) as JS;
}

function deref(s: JS, defs: Record<string, JS>): JS {
  if (s.$ref) {
    const name = s.$ref.split("/").pop()!;
    const target = defs[name] ?? {};
    return { ...deref(target, defs), description: s.description ?? target.description };
  }
  return s;
}

function unwrapNullable(s: JS, defs: Record<string, JS>): { schema: JS; nullable: boolean } {
  const d = deref(s, defs);
  const variants = d.anyOf ?? d.oneOf;
  if (variants) {
    const nonNull = variants.filter((v) => deref(v, defs).type !== "null");
    if (nonNull.length === 1 && nonNull.length < variants.length) {
      const inner = deref(nonNull[0], defs);
      return { schema: { ...inner, description: d.description ?? inner.description, default: d.default ?? inner.default }, nullable: true };
    }
  }
  if (Array.isArray(d.type) && d.type.includes("null")) {
    return { schema: { ...d, type: d.type.find((t) => t !== "null") }, nullable: true };
  }
  return { schema: d, nullable: false };
}

function typeLabel(s: JS, defs: Record<string, JS>): string {
  const d = deref(s, defs);
  if (d.enum) return "enum";
  if (d.const !== undefined) return `\`${JSON.stringify(d.const)}\``;
  if (d.type === "array" && d.items) {
    const inner = unwrapNullable(d.items, defs).schema;
    return `${typeLabel(inner, defs)}[]`;
  }
  if (d.anyOf || d.oneOf) return (d.anyOf ?? d.oneOf)!.map((v) => typeLabel(v, defs)).join(" \\| ");
  const fmt = d.format === "date-time" ? " (date-time)" : d.format === "date" ? " (date)" : d.format === "uri" ? " (url)" : d.format === "email" ? " (email)" : "";
  if (d.type === "object" && d.additionalProperties && !d.properties) return "object (map)";
  return `${(Array.isArray(d.type) ? d.type.join("|") : d.type) ?? "any"}${fmt}`;
}

function rules(s: JS, defs: Record<string, JS>): string {
  const d = deref(s, defs);
  const r: string[] = [];
  if (d.enum) r.push(`One of: ${d.enum.map((v) => `\`${String(v)}\``).join(", ")}`);
  if (d.type === "array" && d.items) {
    const inner = unwrapNullable(d.items, defs).schema;
    if (inner.enum) r.push(`Values: ${inner.enum.map((v) => `\`${String(v)}\``).join(", ")}`);
    if (d.minItems !== undefined) r.push(`min ${d.minItems} item(s)`);
    if (d.maxItems !== undefined) r.push(`max ${d.maxItems} items`);
  }
  const min = d.minimum !== undefined && d.minimum !== -MAX_SAFE ? d.minimum : undefined;
  const max = d.maximum !== undefined && d.maximum !== MAX_SAFE ? d.maximum : undefined;
  if (min !== undefined || max !== undefined) {
    r.push(min !== undefined && max !== undefined ? `${min}–${max}` : min !== undefined ? `≥ ${min}` : `≤ ${max}`);
  }
  if (d.minLength !== undefined || d.maxLength !== undefined) {
    r.push(d.minLength && d.maxLength ? `length ${d.minLength}–${d.maxLength}` : d.maxLength ? `max length ${d.maxLength}` : `min length ${d.minLength}`);
  }
  if (d.pattern && d.pattern.length <= 40 && !d.format) r.push(`pattern \`${d.pattern.replace(/\|/g, "\\|")}\``);
  return r.join("; ");
}

const cell = (s: string | undefined) => (s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ");

interface FieldRow {
  name: string;
  type: string;
  required: boolean;
  def: string;
  rules: string;
  description: string;
}

function fieldRows(schema: z.ZodType, io: "input" | "output", maxDepth = 2): FieldRow[] {
  const root = toJson(schema, io);
  const defs = root.$defs ?? {};
  const rows: FieldRow[] = [];
  const walk = (obj: JS, prefix: string, depth: number, parentRequired: boolean) => {
    const d = deref(obj, defs);
    for (const [key, raw] of Object.entries(d.properties ?? {})) {
      const { schema: prop, nullable } = unwrapNullable(raw, defs);
      const required = parentRequired && (d.required ?? []).includes(key);
      const name = `${prefix}${key}`;
      rows.push({
        name,
        type: typeLabel(prop, defs) + (nullable ? " \\| null" : ""),
        required,
        def: prop.default !== undefined ? `\`${JSON.stringify(prop.default)}\`` : raw.default !== undefined ? `\`${JSON.stringify(raw.default)}\`` : "",
        rules: rules(prop, defs),
        description: prop.description ?? raw.description ?? "",
      });
      if (depth < maxDepth) {
        if (prop.type === "object" && prop.properties) walk(prop, `${name}.`, depth + 1, true);
        if (prop.type === "array" && prop.items) {
          const item = unwrapNullable(prop.items, defs).schema;
          if (item.type === "object" && item.properties) walk(item, `${name}[].`, depth + 1, true);
        }
      }
    }
  };
  walk(root, "", 0, true);
  return rows;
}

function fieldTable(rows: FieldRow[], withDefault = true): string {
  if (!rows.length) return "_None._\n";
  const head = withDefault ? "| Name | Type | Required | Default | Validation | Description |\n|---|---|---|---|---|---|" : "| Field | Type | Required | Validation | Description |\n|---|---|---|---|---|";
  const body = rows
    .map((r) =>
      withDefault
        ? `| \`${r.name}\` | ${r.type} | ${r.required ? "yes" : "no"} | ${r.def} | ${cell(r.rules)} | ${cell(r.description)} |`
        : `| \`${r.name}\` | ${r.type} | ${r.required ? "yes" : "no"} | ${cell(r.rules)} | ${cell(r.description)} |`,
    )
    .join("\n");
  return `${head}\n${body}\n`;
}

const anchor = (e: EndpointDefinition) => `op-${e.operationId.toLowerCase()}`;

function authText(e: EndpointDefinition): string {
  if (e.auth === "PUBLIC") return "Not required — public endpoint.";
  if (e.auth === "OPTIONAL") return "Optional — works without login; if the session cookie is present it is used (e.g. owners/staff can see unpublished records).";
  return "Required — `oceanx_session` cookie (log in first).";
}

function rolesText(e: EndpointDefinition): string {
  if (e.auth !== "REQUIRED") return "Anyone";
  return e.roles ? e.roles.map((r) => `\`${r}\``).join(", ") : "Any logged-in user";
}

function shortPage(page: string) {
  return page.replace(/\s*\(`[^)]*`\)/g, "").replace(/`/g, "");
}

function clientArgs(e: EndpointDefinition, ex: Example | undefined): string {
  const args: string[] = [];
  const js = (v: unknown) => JSON.stringify(v, null, 2).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:").replace(/\n/g, "\n  ");
  if (e.request?.params) args.push(JSON.stringify(ex?.params?.id ?? "<id>"));
  if (e.request?.body) args.push(js(ex?.body ?? {}));
  if (e.request?.query) args.push(js(ex?.query ?? {}));
  return args.join(", ");
}

function tsExample(e: EndpointDefinition, ex: Example | undefined): string {
  const fn = e.client.fn;
  const mod = e.client.module;
  if (e.operationId === "downloadFile") {
    return `import { getFileDownloadUrl } from "@/lib/api/files";\n\n// Render as a normal link — do not fetch():\n<a href={getFileDownloadUrl(${JSON.stringify(ex?.params?.id ?? "<id>")})} download>Download</a>;`;
  }
  if (e.operationId === "putUploadContent") {
    return `import { uploadFile } from "@/lib/api/files";\n\n// uploadFile() performs createUpload → PUT bytes → completeUpload:\nconst file = await uploadFile(input.files[0], { purpose: "COVER_IMAGE", onProgress: (p) => setProgress(p) });`;
  }
  const isList = e.response.schema && "pagination" in (toJson(e.response.schema, "output").properties ?? {});
  const destructure = isList ? "{ data, pagination }" : "{ data }";
  return [
    `import { ${fn} } from "@/lib/api/${mod}";`,
    `import { isApiRequestError } from "@/lib/api-client";`,
    "",
    "try {",
    `  const ${destructure} = await ${fn}(${clientArgs(e, ex)});`,
    "} catch (error) {",
    "  if (isApiRequestError(error)) {",
    "    // error.code: " + Object.keys(e.errors).map((s) => ERROR_STATUS_CODES[Number(s) as ErrorStatus]).join(" | "),
    "    // error.fieldErrors for VALIDATION_ERROR, error.requestId for bug reports",
    "  }",
    "}",
  ].join("\n");
}

function rawFetchExample(e: EndpointDefinition, ex: Example | undefined): string {
  if (e.operationId === "downloadFile" || e.operationId === "putUploadContent") return "";
  const url = `${API_BASE_PATH}${e.path.replace(/\{(\w+)\}/g, (_, k: string) => ex?.params?.[k] ?? `<${k}>`)}${serializeQuery(ex?.query)}`;
  const init: string[] = [`  method: "${e.method}",`, `  credentials: "include", // sends the session cookie`];
  if (e.request?.body) {
    init.push(`  headers: { "Content-Type": "application/json" },`);
    init.push(`  body: JSON.stringify(${JSON.stringify(ex?.body ?? {})}),`);
  }
  return [
    `const res = await fetch(\`\${process.env.NEXT_PUBLIC_API_BASE_URL ?? "/api/v1"}${url.slice(API_BASE_PATH.length)}\`, {`,
    ...init,
    "});",
    "const body = await res.json();",
    "if (!res.ok) throw new Error(`${body.error.code}: ${body.error.message} (requestId ${body.error.requestId})`);",
    "console.log(body.data);",
  ].join("\n");
}

function endpointSection(e: EndpointDefinition, ex: Example | undefined): string {
  const out: string[] = [];
  const statusBadge = { IMPLEMENTED: "✅ IMPLEMENTED", IN_PROGRESS: "🚧 IN_PROGRESS", PLANNED: "📝 PLANNED", DEPRECATED: "⛔ DEPRECATED" }[e.status];
  out.push(`<a id="${anchor(e)}"></a>`, "", `### ${e.summary}`, "", `\`${e.method} ${API_BASE_PATH}${e.path}\``, "");
  out.push("| | |", "|---|---|");
  out.push(`| **API** | ${e.summary} |`);
  out.push(`| **Method** | \`${e.method}\` |`);
  out.push(`| **Endpoint** | \`${API_BASE_PATH}${e.path}\` |`);
  out.push(`| **Operation ID** | \`${e.operationId}\` |`);
  out.push(`| **Status** | ${statusBadge} |`);
  out.push(`| **Authentication** | ${authText(e)} |`);
  out.push(`| **Allowed roles** | ${rolesText(e)} |`);
  out.push(`| **Public / protected** | ${e.auth === "REQUIRED" ? "Protected" : "Public"} |`);
  if (e.rateLimit) out.push(`| **Rate limit** | ${e.rateLimit.limit} requests per ${e.rateLimit.windowSeconds}s per ${e.rateLimit.scope === "ip" ? "IP address" : "user"} |`);
  out.push(`| **Used by** | ${e.frontend.pages.join("<br>")} |`);
  out.push(`| **UI owner** | ${e.frontend.owner === "public-frontend" ? "Public frontend" : "Backend / admin UI"} |`);
  out.push(`| **Client function** | \`${e.client.fn}()\` — \`@/lib/api/${e.client.module}\` |`);
  out.push(`| **Mock** | Available (\`NEXT_PUBLIC_USE_MOCK_API=true\`) |`, "");
  out.push(`**Purpose.** ${e.description}`, "");
  if (e.deprecated) out.push(`> ⛔ Deprecated since ${e.deprecated.since}.${e.deprecated.replacement ? ` Use ${e.deprecated.replacement}.` : ""}${e.deprecated.removal ? ` Removal: ${e.deprecated.removal}.` : ""}`, "");

  // Request
  out.push("#### Request", "");
  const req = e.request;
  if (req?.params) out.push("**Path parameters**", "", fieldTable(fieldRows(req.params, "input"), false));
  if (req?.query) out.push("**Query parameters**", "", fieldTable(fieldRows(req.query, "input")));
  if (req?.body) out.push("**Body** — `application/json`", "", fieldTable(fieldRows(req.body, "input")));
  if (req?.bodyContentType === "application/octet-stream") out.push("**Body** — raw file bytes (`application/octet-stream` or the declared content type). Not multipart.", "");
  if (!req?.params && !req?.query && !req?.body && !req?.bodyContentType) out.push("No parameters or body.", "");
  const exampleUrl = `${e.method} ${API_BASE_PATH}${e.path.replace(/\{(\w+)\}/g, (_, k: string) => ex?.params?.[k] ?? `{${k}}`)}${serializeQuery(ex?.query)}`;
  out.push("Example:", "", "```http", exampleUrl + (ex?.body ? `\nContent-Type: application/json\n\n${JSON.stringify(ex.body, null, 2)}` : ""), "```", "");

  // Response
  out.push(`#### Response \`${e.response.status}\``, "", e.response.description, "");
  if (e.response.headers) {
    out.push("| Header | Value |", "|---|---|", ...Object.entries(e.response.headers).map(([k, v]) => `| \`${k}\` | ${cell(v)} |`), "");
  }
  if (e.response.schema) {
    const rows = fieldRows(e.response.schema, "output", 3).filter((r) => r.name.startsWith("data") || r.name === "pagination" || r.name.startsWith("meta"));
    if (ex?.response) {
      out.push("```json", JSON.stringify(trimExample(ex.response), null, 2), "```", "");
      out.push(
        e.status === "IMPLEMENTED"
          ? "> Example generated from the demo dataset (arrays trimmed). Field shapes are exact."
          : `> **Illustrative example** — this endpoint is **${e.status}**. The structure is the agreed contract and is exactly what the mock API returns; values are demo data (arrays trimmed).`,
        "",
      );
    } else if (ex?.error) {
      out.push(`> No example available (${ex.error}).`, "");
    }
    out.push("<details><summary>Response fields</summary>", "", fieldTable(rows, false), "</details>", "");
  }

  // Errors
  out.push("#### Errors", "", "| Status | `error.code` | When |", "|---|---|---|");
  for (const [status, reason] of Object.entries(e.errors)) {
    out.push(`| ${status} | \`${ERROR_STATUS_CODES[Number(status) as ErrorStatus]}\` | ${cell(reason)} |`);
  }
  out.push("");

  // Frontend integration
  out.push("#### Frontend integration", "");
  out.push(`- **Pages:** ${e.frontend.pages.join(", ")}`);
  out.push(`- **When to call:** ${e.frontend.when}`);
  out.push(`- **Caching:** ${e.frontend.caching}`);
  out.push(`- **Authentication handling:** ${e.auth === "REQUIRED" ? "The browser sends the session cookie automatically. On `UNAUTHENTICATED` redirect to `/login?next=…`; on `FORBIDDEN` show a no-access message." : e.auth === "OPTIONAL" ? "Nothing to do — works logged out; the cookie is sent automatically when present." : "None."}`);
  for (const note of e.frontend.notes ?? []) out.push(`- ${note}`);
  out.push("");
  out.push("```ts", tsExample(e, ex), "```", "");
  const raw = rawFetchExample(e, ex);
  if (raw) out.push("<details><summary>Plain <code>fetch</code> equivalent</summary>", "", "```ts", raw, "```", "", "</details>", "");
  out.push("[↑ Back to endpoint table](#2-endpoint-summary)", "", "---", "");
  return out.join("\n");
}

function statusCounts(): string {
  const counts = Object.fromEntries(STATUSES.map((s) => [s, endpointList.filter((e) => e.status === s).length]));
  return [
    "| Status | Count | Meaning |",
    "|---|---|---|",
    `| ✅ IMPLEMENTED | ${counts.IMPLEMENTED} | Served by the backend and covered by contract tests. |`,
    `| 🚧 IN_PROGRESS | ${counts.IN_PROGRESS} | Partially implemented; may still change. |`,
    `| 📝 PLANNED | ${counts.PLANNED} | Contract agreed; not implemented yet. Use the mock API. |`,
    `| ⛔ DEPRECATED | ${counts.DEPRECATED} | Still served; do not use in new code. |`,
    `| **Total** | **${endpointList.length}** | |`,
    "",
  ].join("\n");
}

function endpointTable(): string {
  const rows = API_TAGS.flatMap((tag) =>
    endpointList
      .filter((e) => e.tag === tag)
      .map(
        (e) =>
          `| ${e.method} | [\`${API_BASE_PATH}${e.path}\`](#${anchor(e)}) | ${cell(e.summary)} | ${e.auth === "REQUIRED" ? (e.roles ? e.roles.join(", ") : "Logged in") : e.auth === "OPTIONAL" ? "Public (optional session)" : "Public"} | ${cell(e.frontend.pages.map(shortPage).join(", "))} | ${e.status} |`,
      ),
  );
  return ["| Method | Endpoint | Purpose | Authentication | Frontend Page | Status |", "|---|---|---|---|---|---|", ...rows, ""].join("\n");
}

function endpointReference(examples: Map<string, Example>): string {
  const out: string[] = [];
  API_TAGS.forEach((tag, i) => {
    const eps = endpointList.filter((e) => e.tag === tag);
    if (!eps.length) return;
    out.push(`## 4.${i + 1} ${tag}`, "", TAG_DESCRIPTIONS[tag], "");
    for (const e of eps) out.push(endpointSection(e, examples.get(e.operationId)));
  });
  return out.join("\n");
}

function pageApiMap(): string {
  const byPage = new Map<string, EndpointDefinition[]>();
  for (const e of endpointList) {
    if (e.frontend.owner !== "public-frontend") continue;
    for (const p of e.frontend.pages) {
      if (/^Admin|Contributor|Monitoring/.test(p)) continue;
      byPage.set(p, [...(byPage.get(p) ?? []), e]);
    }
  }
  const rows = [...byPage.entries()].map(
    ([page, eps]) =>
      `| ${page} | ${eps.map((e) => `\`${e.client.fn}()\``).join("<br>")} | ${eps.map((e) => `\`${e.method} ${e.path}\``).join("<br>")} | ${eps.map((e) => e.status).join("<br>")} |`,
  );
  return ["| Page | Client functions | Endpoints (under `/api/v1`) | Status |", "|---|---|---|---|", ...rows, ""].join("\n");
}

function replaceBlock(doc: string, name: string, content: string, file: string): string {
  const begin = `<!-- BEGIN GENERATED: ${name} -->`;
  const end = `<!-- END GENERATED: ${name} -->`;
  const i = doc.indexOf(begin);
  const j = doc.indexOf(end);
  if (i < 0 || j < 0) throw new Error(`Markers for "${name}" not found in ${file}`);
  return `${doc.slice(0, i + begin.length)}\n<!-- Do not edit: generated by \`npm run api:generate\` -->\n\n${content}\n${doc.slice(j)}`;
}

